export const getMealOptions = (
  bodyType: 'slim' | 'strong' | 'steady',
  mealTime: 'breakfast' | 'lunch' | 'supper'
): MealOption[] => {
  return MEAL_OPTIONS.filter(
    (meal) => meal.body_type === bodyType && meal.meal_time === mealTime
  );
};

export const getBodyTypeFromArchetype = (
  archetype: string | null
): 'slim' | 'strong' | 'steady' | null => {
  if (!archetype) return null;
  if (archetype === 'runner') return 'slim';
  if (archetype === 'warrior') return 'strong';
  if (archetype === 'guardian') return 'steady';
  return null;
};