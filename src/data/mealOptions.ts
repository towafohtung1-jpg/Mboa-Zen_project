export const getMealOptions = (
  bodyType: string,
  mealTime: 'breakfast' | 'lunch' | 'supper'
): MealOption[] => {
  return MEAL_OPTIONS.filter(
    (meal) => meal.meal_time === mealTime
  );
};

export const getBodyTypeFromArchetype = (archetype: string | null): string | null => {
  if (!archetype) return null;
  const map: Record<string, string> = {
    runner: 'slim',
    warrior: 'strong',
    guardian: 'steady',
  };
  return map[archetype] || null;
};
